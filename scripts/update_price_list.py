#!/usr/bin/env python3
"""Writes the price list a Flux release ships (#1465): LiteLLM's model price file as fetched today.

  python3 scripts/update_price_list.py            fetch the list and rewrite the shipped snapshot
  python3 scripts/update_price_list.py --check N  fail when the shipped snapshot is older than N days

A Flux server refreshes its prices every day from the same file (the worker's price list job). The image build stays offline and
reproducible, so the snapshot is a checked-in file: the release procedure runs this script on the build day and commits the result
into the candidate (docs/agents/ci-and-releases.md), and the final release workflow checks its date. Only the entries Flux can use are
kept (Anthropic's, OpenAI's and Gemini's text models) with only their standard and prompt-length prices; which of them become Flux's
prices is decided at run time by the same code that reads the daily list (`parsePriceList` in app/packages/core/src/ai/price-list.ts).
Nothing is sent but an anonymous GET.
"""

from __future__ import annotations

import datetime as dt
import json
import re
import sys
import urllib.request
from pathlib import Path

URL = "https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json"
SNAPSHOT = Path(__file__).resolve().parent.parent / "app/packages/core/src/ai/price-list-snapshot.ts"
MAX_BYTES = 16_000_000
PROVIDERS = {"anthropic", "openai", "gemini"}
MODES = {"chat", "responses"}
FIELD = re.compile(r"^(input|output)_cost_per_token(_above_\d{1,4}k_tokens)?$")
DATE = re.compile(r"fetchedOn: '(\d{4}-\d{2}-\d{2})'")


def fetch() -> dict:
    request = urllib.request.Request(URL, headers={"Accept": "application/json", "User-Agent": "flux-price-list"})
    with urllib.request.urlopen(request, timeout=60) as response:  # noqa: S310 - fixed https address
        body = response.read(MAX_BYTES + 1)
    if len(body) > MAX_BYTES:
        raise SystemExit(f"The price file is larger than {MAX_BYTES} bytes; nothing was written.")
    data = json.loads(body)
    if not isinstance(data, dict):
        raise SystemExit("The price file is not a JSON object; nothing was written.")
    return data


def kept(data: dict) -> dict:
    entries = {}
    for key, value in sorted(data.items()):
        if not isinstance(value, dict) or value.get("litellm_provider") not in PROVIDERS or value.get("mode") not in MODES:
            continue
        fields = {name: value[name] for name in sorted(value) if FIELD.match(name) and isinstance(value[name], (int, float))}
        if "input_cost_per_token" in fields and "output_cost_per_token" in fields:
            entries[key] = {"litellm_provider": value["litellm_provider"], "mode": value["mode"], **fields}
    if not all(any(entry["litellm_provider"] == provider for entry in entries.values()) for provider in PROVIDERS):
        raise SystemExit("The price file has no priced text model of Anthropic, OpenAI or Gemini; nothing was written.")
    return entries


def write(entries: dict, today: str) -> None:
    body = json.dumps(entries, indent=1, sort_keys=True)
    SNAPSHOT.write_text(
        "// Generated by scripts/update_price_list.py: the price list this release ships (#1465). Do not edit by hand.\n"
        "// LiteLLM's model price file, Copyright (c) 2023 Berri AI, MIT licence (the notice is in NOTICE): only Anthropic's, OpenAI's and\n"
        "// Gemini's text models and their standard and prompt-length prices; `parsePriceList` (price-list.ts) turns it into Flux's prices\n"
        "// exactly as it does the daily list.\n"
        f"export const SHIPPED_PRICE_FILE: {{ fetchedOn: string; source: string; entries: Record<string, Record<string, unknown>> }} = {{\n"
        f"  fetchedOn: '{today}',\n  source: '{URL}',\n  entries: {body},\n}};\n",
        encoding="utf-8",
    )


def check(days: int) -> int:
    match = DATE.search(SNAPSHOT.read_text(encoding="utf-8"))
    if not match:
        print(f"{SNAPSHOT} has no fetchedOn date", file=sys.stderr)
        return 1
    age = (dt.date.today() - dt.date.fromisoformat(match.group(1))).days
    if age > days:
        print(f"The shipped price list was fetched on {match.group(1)}, {age} days ago (at most {days}). "
              "Run python3 scripts/update_price_list.py and commit the snapshot into the candidate.", file=sys.stderr)
        return 1
    print(f"Shipped price list fetched on {match.group(1)} ({age} days ago)")
    return 0


def main(argv: list[str]) -> int:
    if len(argv) == 2 and argv[0] == "--check":
        return check(int(argv[1]))
    if argv:
        print(__doc__, file=sys.stderr)
        return 2
    entries = kept(fetch())
    today = dt.datetime.now(dt.timezone.utc).date().isoformat()
    write(entries, today)
    print(f"Wrote {len(entries)} models fetched on {today} to {SNAPSHOT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
